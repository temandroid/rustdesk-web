#!/bin/sh
# Renders /rd-config.js from environment variables (nginx image runs every
# /docker-entrypoint.d/*.sh before starting). The core applies these as
# defaults for options the user has not set; RD_FORCE_CONFIG=true overrides.
#
#   RD_ID_SERVER     ID server host, e.g. rdweb.example.com
#                    (domain form -> wss://host/ws/id and /ws/relay)
#   RD_API_SERVER    e.g. https://rdweb.example.com (same origin as this site)
#   RD_RELAY_SERVER  optional relay host (usually empty)
#   RD_KEY           server public key (contents of id_ed25519.pub)
#   RD_ICE_SERVERS   optional, comma separated stun:/turn://user:pass@host:port
#   RD_FORCE_CONFIG  "true" to overwrite stored settings on every load
set -eu

out=${RD_CONFIG_OUT:-/usr/share/nginx/html/rd-config.js}

# JSON string escaping for the handful of characters that matter here.
esc() {
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

force=false
case "${RD_FORCE_CONFIG:-}" in
  1|true|TRUE|yes|YES|y|Y) force=true ;;
esac

{
  printf '// generated by docker/10-rd-config.sh\n'
  printf 'window.RD_CONFIG = {\n'
  printf '  "idServer": "%s",\n' "$(esc "${RD_ID_SERVER:-}")"
  printf '  "apiServer": "%s",\n' "$(esc "${RD_API_SERVER:-}")"
  printf '  "relayServer": "%s",\n' "$(esc "${RD_RELAY_SERVER:-}")"
  printf '  "key": "%s",\n' "$(esc "${RD_KEY:-}")"
  printf '  "iceServers": "%s",\n' "$(esc "${RD_ICE_SERVERS:-}")"
  printf '  "force": %s\n' "$force"
  printf '};\n'
} > "$out"

echo "rd-config.js rendered (id server: ${RD_ID_SERVER:-<unset>}, key: $([ -n "${RD_KEY:-}" ] && echo set || echo unset))"
